export interface ProjectProfile {
  id: string;
  name: string;
  /**
   * Names of files that, if detected in the root, identify this project type.
   */
  detectFiles: string[];
  /**
   * Function to detect if this profile matches the given root path.
   */
  detect: (root: string) => boolean;
  /**
   * Optional: Custom logic to detect the profile.
   * Returns a string describing what was matched (e.g. "next"), or null if no match.
   */
  customDetect?: (root: string, fs: any, path: any) => string | null;
  /**
   * Extensions that are most relevant to this project type.
   */
  targetExts: string[];
  /**
   * Folders generated by the framework itself (build output, cache).
   * Only include directories officially produced by the framework's CLI/build tools.
   */
  ignoreFolders: string[];
  /**
   * Folders containing external libraries or dependencies (e.g. "node_modules", "vendor").
   */
  dependencyFolders?: string[];
  /**
   * Official documentation URLs used to derive this profile's configuration.
   * Enables future maintainers to trace and verify each setting.
   * Supports either a raw URL string or an object with a descriptive label.
   */
  sourceUrls?: (string | { label: string; url: string })[];
  /**
   * Automatically injected: The path to the file that defined this profile.
   */
  sourceFile?: string;

  /**
   * Describes the type of logic used for analysis (e.g. "JavaScript Logic").
   */
  analysisLogic?: string;
  /**
   * Describes specific features supported by this logic (e.g. "Supports React, Next.js...").
   */
  logicFeatures?: string;
  /**
   * Optional: Icon representing this project type (e.g. "⚛️", "🐍").
   */
  icon?: string;

  // Metadata captured during detection
  detectionInfo?: {
    matchedFile?: string;
    matchedDetail?: string;
  };
}
