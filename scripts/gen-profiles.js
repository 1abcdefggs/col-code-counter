/**
 * Auto-generates src/profiles/index.ts by scanning profile files.
 * Run: node scripts/gen-profiles.js
 */
const fs = require("fs");
const path = require("path");

const PROFILES_DIR = path.join(__dirname, "..", "src", "profiles");
const OUTPUT_FILE = path.join(PROFILES_DIR, "index.ts");

const files = fs
  .readdirSync(PROFILES_DIR, { withFileTypes: true })
  .filter(
    (f) =>
      f.isFile() &&
      f.name.endsWith(".ts") &&
      f.name !== "index.ts" &&
      f.name !== "types.ts"
  )
  .map((f) => f.name.replace(".ts", ""))
  .sort();

// Separate 'generic' to always be last (fallback)
const specific = files.filter((f) => f !== "generic");
const hasGeneric = files.includes("generic");

let lines = [
  "// AUTO-GENERATED by scripts/gen-profiles.js — do not edit manually",
  'import { ProjectProfile } from "./types";',
  "",
];

for (const name of specific) {
  lines.push(`import ${name} from "./${name}";`);
}
if (hasGeneric) {
  lines.push(`import generic from "./generic";`);
}

lines.push("");
lines.push("export const profiles: ProjectProfile[] = [");
for (const name of specific) {
  lines.push(`  ...${name}.map(p => ({ ...p, sourceFile: "src/profiles/${name}.ts" })),`);
}
if (hasGeneric) {
  lines.push(`  ...generic.map(p => ({ ...p, sourceFile: "src/profiles/generic.ts" })),`);
}
lines.push("];");
lines.push("");

fs.writeFileSync(OUTPUT_FILE, lines.join("\n"), "utf8");
console.log(
  `Generated ${OUTPUT_FILE} with ${files.length} profile files.`
);
